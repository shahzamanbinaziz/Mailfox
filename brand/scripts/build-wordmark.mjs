// Generates every logo SVG in /brand from the mark geometry + the Plus Jakarta Sans
// wordmark converted to outlines (so the SVGs never depend on an installed font).
// Run: node brand/scripts/build-wordmark.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";
import { COLORS, markGroup, monoGroup, MARK } from "./mark-geometry.mjs";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const brandDir = join(here, "..");

const fontPath =
  require.resolve("@fontsource/plus-jakarta-sans/files/plus-jakarta-sans-latin-800-normal.woff");
const buf = readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const WORD = "Mailfox";
const FONT_SIZE = 42;
const TRACKING = -0.6; // px between glyphs, slightly tight for a confident wordmark
const GAP = 14; // space between mark and wordmark

// Lay out glyph by glyph to apply tracking.
function wordPath() {
  let x = 0;
  const paths = [];
  // Map chars directly (skips opentype.js's shaping engine, which chokes on this font's GSUB).
  const glyphs = [...WORD].map((ch) => font.charToGlyph(ch));
  glyphs.forEach((g, i) => {
    paths.push(g.getPath(x, 0, FONT_SIZE));
    const next = glyphs[i + 1];
    const kern = next ? font.getKerningValue(g, next) : 0;
    x += ((g.advanceWidth + kern) / font.unitsPerEm) * FONT_SIZE + TRACKING;
  });
  const merged = new opentype.Path();
  for (const p of paths) merged.extend(p);
  return merged;
}

const word = wordPath();
const bb = word.getBoundingBox();
const wordWidth = bb.x2 - bb.x1;
const wordHeight = bb.y2 - bb.y1;
// Center the wordmark on the envelope body's optical center.
const bodyCenterY = MARK.body.y + MARK.body.height / 2 - 2;
const tx = 64 + GAP - bb.x1;
const ty = bodyCenterY - (bb.y1 + wordHeight / 2);
const d = word.toPathData(2);
const totalW = Math.ceil(64 + GAP + wordWidth + 2);

const svg = (w, h, body, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-labelledby="t">
<title id="t">${title}</title>
${body}
</svg>
`;

const wordmark = (fill) =>
  `<path transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)})" fill="${fill}" d="${d}"/>`;

const files = {
  "logo-mark.svg": svg(64, 64, markGroup({ id: "mf" }), "Mailfox"),
  "logo-mark-mono.svg": svg(64, 64, monoGroup({ id: "mfm" }), "Mailfox"),
  "logo-full.svg": svg(totalW, 64, `${markGroup({ id: "mf" })}\n${wordmark(COLORS.ink)}`, "Mailfox"),
  "logo-full-dark.svg": svg(totalW, 64, `${markGroup({ id: "mf" })}\n${wordmark(COLORS.white)}`, "Mailfox"),
  "logo-mono.svg": svg(totalW, 64, `${monoGroup({ id: "mfm" })}\n${wordmark("currentColor")}`, "Mailfox"),
  // Favicon: same mark, no title needed.
  "icons/favicon.svg": `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">\n${markGroup({ id: "fv" })}\n</svg>\n`,
};

mkdirSync(join(brandDir, "icons"), { recursive: true });
for (const [name, content] of Object.entries(files)) {
  writeFileSync(join(brandDir, name), content);
  console.log("wrote brand/" + name);
}

// Export the wordmark path for the React <Logo/> component.
const uiOut = join(brandDir, "..", "packages", "ui", "src", "brand", "wordmark.ts");
mkdirSync(dirname(uiOut), { recursive: true });
writeFileSync(
  uiOut,
  `// AUTO-GENERATED by brand/scripts/build-wordmark.mjs — do not edit.\n` +
    `export const WORDMARK = {\n  width: ${totalW},\n  transform: "translate(${tx.toFixed(2)} ${ty.toFixed(2)})",\n  d: ${JSON.stringify(d)},\n} as const;\n`,
);
console.log("wrote packages/ui/src/brand/wordmark.ts");
