// Generates src/styles/tokens.css from src/tokens.ts.
// Output = Tailwind v4 `@theme` (palette + fonts + radius) and light/dark semantic CSS variables.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { colors, radius, semantic, typography, scaleSteps } from "../src/tokens";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "styles", "tokens.css");

const lines: string[] = [];
lines.push("/* AUTO-GENERATED by packages/ui/scripts/build-tokens.ts — edit src/tokens.ts instead. */");
lines.push("");
lines.push("@theme {");
for (const [name, scale] of Object.entries(colors)) {
  for (const step of scaleSteps) lines.push(`  --color-${name}-${step}: ${scale[step]};`);
}
lines.push(`  --font-sans: ${typography.sans};`);
lines.push(`  --font-mono: ${typography.mono};`);
for (const [k, v] of Object.entries(radius)) lines.push(`  --radius-${k}: ${v};`);
lines.push("}");
lines.push("");

// Semantic tokens → raw CSS variables (light on :root, dark on .dark and prefers-color-scheme fallback)
const block = (selector: string, theme: Record<string, string>) => {
  lines.push(`${selector} {`);
  for (const [k, v] of Object.entries(theme)) lines.push(`  --${k}: ${v};`);
  lines.push("}");
};
block(":root", semantic.light);
lines.push("");
block(".dark", semantic.dark);
lines.push("");
lines.push(":root { color-scheme: light; }");
lines.push(".dark { color-scheme: dark; }");
lines.push("");

// Illustration variables (empty states) for dark mode.
lines.push(
  `.dark {\n  --mf-illu-blob: ${colors.ink[900]};\n  --mf-illu-shadow: ${colors.ink[800]};\n  --mf-illu-paper: ${colors.ink[800]};\n  --mf-illu-line: ${colors.ink[600]};\n  --mf-illu-stroke: ${colors.ink[100]};\n}`,
);
lines.push("");

// Map semantic vars into Tailwind colour utilities (bg-background, text-muted-foreground, ...).
lines.push("@theme inline {");
for (const k of Object.keys(semantic.light)) lines.push(`  --color-${k}: var(--${k});`);
lines.push("}");
lines.push("");

// Shimmer used by <Skeleton/>; disabled for reduced motion.
lines.push(`.mf-skeleton {
  background: linear-gradient(90deg, var(--muted) 25%, color-mix(in oklab, var(--muted), var(--foreground) 6%) 37%, var(--muted) 63%);
  background-size: 400% 100%;
  animation: mf-shimmer 1.4s ease infinite;
}
@keyframes mf-shimmer {
  0% { background-position: 100% 50%; }
  100% { background-position: 0 50%; }
}
@media (prefers-reduced-motion: reduce) {
  .mf-skeleton { animation: none; }
}`);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n") + "\n");
console.log("wrote", out);
